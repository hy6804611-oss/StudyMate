// ==========================================
// SHUFFLE
// ==========================================

shuffleBtn.addEventListener(
    "click",
    () => {

        if (
            flashcards.length <= 1
        ) {

            return;

        }


        let randomCard;


        do {

            randomCard =
                Math.floor(
                    Math.random() *
                    flashcards.length
                );

        } while (
            randomCard === currentCard
        );


        currentCard =
            randomCard;


        saveFlashcardAnalytics(
            "SHUFFLED"
        );


        loadCard();

    }
);


// ==========================================
// FAVORITES
// ==========================================

favoriteBtn.addEventListener(
    "click",
    () => {

        const card =
            flashcards[currentCard];


        const exists =
            favorites.find(
                f =>
                    f.question ===
                    card.question
            );


        if (exists) {

            alert(
                "⭐ This flashcard is already in your favorites."
            );

            return;

        }


        // ----------------------------------
        // FREE FAVORITE LIMIT
        // ----------------------------------

        if (
            favorites.length >= 10
        ) {

            alert(

                "⭐ Free users can save only 10 favorites.\n\n" +

                "Upgrade to StudyMate Premium for unlimited favorites."

            );

            return;

        }


        favorites.push({

            subject:
                SUBJECT,

            question:
                card.question,

            answer:
                card.answer

        });


        localStorage.setItem(

            "favorites",

            JSON.stringify(
                favorites
            )

        );


        alert(
            "⭐ Flashcard added to Favorites!"
        );

    }
);


