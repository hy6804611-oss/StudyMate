function getFlashcardAnalytics() {

    try {

        return JSON.parse(
            localStorage.getItem(
                "studyMateFlashcardAnalytics"
            )
        ) || {};

    } catch (error) {

        return {};

    }

}


// ==========================================
// SAVE FLASHCARD ANALYTICS
// ==========================================

function saveFlashcardAnalytics(action) {

    try {

        let analytics =
            getFlashcardAnalytics();


        if (!analytics[SUBJECT]) {

            analytics[SUBJECT] = {

                sessions: 0,

                reviewed: 0,

                completed: 0,

                lastReviewed: null

            };

        }


        const subject =
            analytics[SUBJECT];


        // New session

        if (action === "STARTED") {

            subject.sessions++;

        }


        // Card reviewed

        if (action === "CARD_REVIEWED") {

            subject.reviewed++;

            subject.lastReviewed =
                new Date().toISOString();

        }


        // Completed

        if (action === "COMPLETED") {

            subject.completed++;

            subject.lastReviewed =
                new Date().toISOString();

        }


        localStorage.setItem(

            "studyMateFlashcardAnalytics",

            JSON.stringify(analytics)

        );


        // ----------------------------------
        // ALSO SAVE GENERAL ACTIVITY
        // ----------------------------------

        let activities =
            JSON.parse(
                localStorage.getItem(
                    "studyMateActivity"
                )
            ) || [];


        activities.push({

            subject: SUBJECT,

            type: "FLASHCARD",

            action: action,

            cardNumber:
                currentCard + 1,

            totalCards:
                flashcards.length,

            date:
                new Date().toISOString()

        });


        localStorage.setItem(

            "studyMateActivity",

            JSON.stringify(activities)

        );


        // ----------------------------------
        // SIMPLE TOTAL FLASHCARD COUNT
        // ----------------------------------

        let totalReviewed = 0;


        Object.values(analytics)
            .forEach(data => {

                totalReviewed +=
                    Number(data.reviewed) || 0;

            });


        localStorage.setItem(

            "flashcardsReviewed",

            totalReviewed

        );


        // ----------------------------------
        // SUBJECT-SPECIFIC COUNT
        // ----------------------------------

        localStorage.setItem(

            "flashcards_" +
            SUBJECT,

            subject.reviewed

        );


    } catch (error) {

        console.warn(

            "StudyMate Flashcard Analytics Error:",

            error

        );

    }

}


// ==========================================
// START FLASHCARD SESSION
// ==========================================

saveFlashcardAnalytics(
    "STARTED"
);


// ==========================================
// CARD COUNTER
// ==========================================

function updateCardCounter() {

    if (!cardCounter) {
        return;
    }

    cardCounter.innerHTML =

        `📖 Card ${currentCard + 1} of ${flashcards.length}`;

}


// ==========================================
// LOAD CARD
// ==========================================

function loadCard() {

    if (!flashcards.length) {
        return;
    }


    document.querySelector(
        ".card-front .card-content"
    ).innerHTML =

        flashcards[currentCard].question;


    document.querySelector(
        ".card-back .card-content"
    ).innerHTML =

        flashcards[currentCard].answer;


    showingAnswer = false;


    flashcard.classList.remove(
        "flipped"
    );


    updateCardCounter();


    const percent =

        (
            (currentCard + 1) /
            flashcards.length
        ) * 100;


    if (progressFill) {

        progressFill.style.width =
            percent + "%";

    }


    if (progressPercent) {

        progressPercent.innerHTML =
            Math.round(percent) + "%";

    }


    if (progressCount) {

        progressCount.innerHTML =

            (currentCard + 1) +
            " / " +
            flashcards.length;

    }

}


// ==========================================
// FLIP CARD
// ==========================================

flashcard.addEventListener(
    "click",
    () => {

        flashcard.classList.toggle(
            "flipped"
        );

        showingAnswer =
            !showingAnswer;

    }
);


// ==========================================
// NEXT CARD
// ==========================================

nextBtn.addEventListener(
    "click",
    () => {

        currentCard++;


        // ----------------------------------
        // ALL CARDS COMPLETED
        // ----------------------------------

        if (
            currentCard >=
            flashcards.length
        ) {

            saveFlashcardAnalytics(
                "COMPLETED"
            );


            localStorage.setItem(

                "flashcardCompleted",

                "true"

            );


            localStorage.setItem(

                "flashcardSubject",

                SUBJECT

            );


            window.location.href =
                "flashcardcompleted.html";


            return;

        }


        // ----------------------------------
        // RECORD REVIEWED CARD
        // ----------------------------------

        saveFlashcardAnalytics(

            "CARD_REVIEWED"

        );


        loadCard();

    }
);


// ==========================================
// PREVIOUS CARD
// ==========================================

previousBtn.addEventListener(
    "click",
    () => {

        if (currentCard === 0) {

            alert(
                "📖 You are already on the first flashcard."
            );

            return;

        }


        currentCard--;

        loadCard();

    }
);


// ==========================================
// SHUFFLE
// ==========================================

shuffleBtn.addEventListener(
    "click",
    () => {

        if (
            flashcards.length <= 1
        ) {

            return;

        }


        let randomCard;


        do {

            randomCard =
                Math.floor(
                    Math.random() *
                    flashcards.length
                );

        } while (
            randomCard === currentCard
        );


        currentCard =
            randomCard;


        saveFlashcardAnalytics(
            "SHUFFLED"
        );


        loadCard();

    }
);


// ==========================================
// FAVORITES
// ==========================================

favoriteBtn.addEventListener(
    "click",
    () => {

        const card =
            flashcards[currentCard];


        const exists =
            favorites.find(
                f =>
                    f.question ===
                    card.question
            );


        if (exists) {

            alert(
                "⭐ This flashcard is already in your favorites."
            );

            return;

        }


        // ----------------------------------
        // FREE FAVORITE LIMIT
        // ----------------------------------

        if (
            favorites.length >= 10
        ) {

            alert(

                "⭐ Free users can save only 10 favorites.\n\n" +

                "Upgrade to StudyMate Premium for unlimited favorites."

            );

            return;

        }


        favorites.push({

            subject:
                SUBJECT,

            question:
                card.question,

            answer:
                card.answer

        });


        localStorage.setItem(

            "favorites",

            JSON.stringify(
                favorites
            )

        );


        alert(
            "⭐ Flashcard added to Favorites!"
        );

    }
);


// ==========================================
// LOAD FIRST CARD
// ==========================================

loadCard();


// ==========================================
// COMPLETION POPUP
// ==========================================

function showCompletionPopup() {

    const restart =
        confirm(

            "🎉 Flashcards Completed!\n\n" +

            "You have studied all " +

            flashcards.length +

            " flashcards.\n\n" +

            "Press OK to Study Again.\n\n" +

            "Press Cancel to go back to Subjects."

        );


    if (restart) {

        currentCard = 0;

        loadCard();

    } else {

        window.location.href =
            "flashcards.html";

    }

}