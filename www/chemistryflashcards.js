function showCompletionPopup() {

    const restart =
        confirm(

            "🎉 Flashcards Completed!\n\n" +

            "You have studied all " +

            flashcards.length +

            " flashcards.\n\n" +

            "Press OK to Study Again.\n\n" +

            "Press Cancel to go back to Subjects."

        );


    if (restart) {

        currentCard = 0;

        loadCard();

    } else {

        window.location.href =
            "flashcards.html";

    }

}