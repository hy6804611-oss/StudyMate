// ==========================================
// GET FLASHCARD ANALYTICS
// ==========================================

function getFlashcardAnalytics() {

    try {

        return JSON.parse(
            localStorage.getItem(
                "studyMateFlashcardAnalytics"
            )
        ) || {};

    } catch (error) {

        return {};

    }

}


// ==========================================
// SAVE FLASHCARD ANALYTICS
// ==========================================

function saveFlashcardAnalytics(action) {

    try {

        let analytics =
            getFlashcardAnalytics();


        if (!analytics[SUBJECT]) {

            analytics[SUBJECT] = {

                sessions: 0,

                reviewed: 0,

                completed: 0,

                lastReviewed: null

            };

        }


        const subject =
            analytics[SUBJECT];


        // New session

        if (action === "STARTED") {

            subject.sessions++;

        }


        // Card reviewed

        if (action === "CARD_REVIEWED") {

            subject.reviewed++;

            subject.lastReviewed =
                new Date().toISOString();

        }


        // Completed

        if (action === "COMPLETED") {

            subject.completed++;

            subject.lastReviewed =
                new Date().toISOString();

        }


        localStorage.setItem(

            "studyMateFlashcardAnalytics",

            JSON.stringify(analytics)

        );


        // ----------------------------------
        // ALSO SAVE GENERAL ACTIVITY
        // ----------------------------------

        let activities =
            JSON.parse(
                localStorage.getItem(
                    "studyMateActivity"
                )
            ) || [];


        activities.push({

            subject: SUBJECT,

            type: "FLASHCARD",

            action: action,

            cardNumber:
                currentCard + 1,

            totalCards:
                flashcards.length,

            date:
                new Date().toISOString()

        });


        localStorage.setItem(

            "studyMateActivity",

            JSON.stringify(activities)

        );


        // ----------------------------------
        // SIMPLE TOTAL FLASHCARD COUNT
        // ----------------------------------

        let totalReviewed = 0;


        Object.values(analytics)
            .forEach(data => {

                totalReviewed +=
                    Number(data.reviewed) || 0;

            });


        localStorage.setItem(

            "flashcardsReviewed",

            totalReviewed

        );


        // ----------------------------------
        // SUBJECT-SPECIFIC COUNT
        // ----------------------------------

        localStorage.setItem(

            "flashcards_" +
            SUBJECT,

            subject.reviewed

        );


    } catch (error) {

        console.warn(

            "StudyMate Flashcard Analytics Error:",

            error

        );

    }

}


// ==========================================
// START FLASHCARD SESSION
// ==========================================

saveFlashcardAnalytics(
    "STARTED"
);


// ==========================================
// CARD COUNTER
// ==========================================

function updateCardCounter() {

    if (!cardCounter) {
        return;
    }

    cardCounter.innerHTML =

        `📖 Card ${currentCard + 1} of ${flashcards.length}`;

}


// ==========================================
// LOAD CARD
// ==========================================

function loadCard() {

    if (!flashcards.length) {
        return;
    }


    document.querySelector(
        ".card-front .card-content"
    ).innerHTML =

        flashcards[currentCard].question;


    document.querySelector(
        ".card-back .card-content"
    ).innerHTML =

        flashcards[currentCard].answer;


    showingAnswer = false;


    flashcard.classList.remove(
        "flipped"
    );


    updateCardCounter();


    const percent =

        (
            (currentCard + 1) /
            flashcards.length
        ) * 100;


    if (progressFill) {

        progressFill.style.width =
            percent + "%";

    }


    if (progressPercent) {

        progressPercent.innerHTML =
            Math.round(percent) + "%";

    }


    if (progressCount) {

        progressCount.innerHTML =

            (currentCard + 1) +
            " / " +
            flashcards.length;

    }

}


