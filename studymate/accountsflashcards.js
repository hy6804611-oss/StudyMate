flashcard.addEventListener(
    "click",
    () => {

        flashcard.classList.toggle(
            "flipped"
        );

        showingAnswer =
            !showingAnswer;

    }
);


// ==========================================
// NEXT CARD
// ==========================================

nextBtn.addEventListener(
    "click",
    () => {

        currentCard++;


        // ----------------------------------
        // ALL CARDS COMPLETED
        // ----------------------------------

        if (
            currentCard >=
            flashcards.length
        ) {

            saveFlashcardAnalytics(
                "COMPLETED"
            );


            localStorage.setItem(

                "flashcardCompleted",

                "true"

            );


            localStorage.setItem(

                "flashcardSubject",

                SUBJECT

            );


            window.location.href =
                "flashcardcompleted.html";


            return;

        }


        // ----------------------------------
        // RECORD REVIEWED CARD
        // ----------------------------------

        saveFlashcardAnalytics(

            "CARD_REVIEWED"

        );


        loadCard();

    }
);


// ==========================================
// PREVIOUS CARD
// ==========================================

previousBtn.addEventListener(
    "click",
    () => {

        if (currentCard === 0) {

            alert(
                "📖 You are already on the first flashcard."
            );

            return;

        }


        currentCard--;

        loadCard();

    }
);


// ==========================================
// SHUFFLE
// ==========================================

shuffleBtn.addEventListener(
    "click",
    () => {

        if (
            flashcards.length <= 1
        ) {

            return;

        }


        let randomCard;


        do {

            randomCard =
                Math.floor(
                    Math.random() *
                    flashcards.length
                );

        } while (
            randomCard === currentCard
        );


        currentCard =
            randomCard;


        saveFlashcardAnalytics(
            "SHUFFLED"
        );


        loadCard();

    }
);


// ==========================================
// FAVORITES
// ==========================================

favoriteBtn.addEventListener(
    "click",
    () => {

        const card =
            flashcards[currentCard];


        const exists =
            favorites.find(
                f =>
                    f.question ===
                    card.question
            );


        if (exists) {

            alert(
                "⭐ This flashcard is already in your favorites."
            );

            return;

        }


        // ----------------------------------
        // FREE FAVORITE LIMIT
        // ----------------------------------

        if (
            favorites.length >= 10
        ) {

            alert(

                "⭐ Free users can save only 10 favorites.\n\n" +

                "Upgrade to StudyMate Premium for unlimited favorites."

            );

            return;

        }


        favorites.push({

            subject:
                SUBJECT,

            question:
                card.question,

            answer:
                card.answer

        });


        localStorage.setItem(

            "favorites",

            JSON.stringify(
                favorites
            )

        );


        alert(
            "⭐ Flashcard added to Favorites!"
        );

    }
);


// ==========================================
// LOAD FIRST CARD
// ==========================================

loadCard();


// ==========================================
// COMPLETION POPUP
// ==========================================

function showCompletionPopup() {

    const restart =
        confirm(

            "🎉 Flashcards Completed!\n\n" +

            "You have studied all " +

            flashcards.length +

            " flashcards.\n\n" +

            "Press OK to Study Again.\n\n" +

            "Press Cancel to go back to Subjects."

        );


    if (restart) {

        currentCard = 0;

        loadCard();

    } else {

        window.location.href =
            "flashcards.html";

    }

}